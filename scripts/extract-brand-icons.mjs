// Copies the SVG paths of the brand icons the site uses out of `simple-icons`
// (CC0) into a small module, so the full icon set never reaches the bundle.
// Run with: npm run icons
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const names = [
  'siAnthropic', 'siDatacamp', 'siDocker', 'siDuckdb', 'siGit', 'siGithub', 'siGoogle', 'siGradio',
  'siJavascript', 'siLangchain', 'siOpencv', 'siPandas', 'siPydantic', 'siPython', 'siSap',
  'siSqlite', 'siStreamlit', 'siTypescript',
];

const body = names
  .map((n) => {
    const icon = si[n];
    if (!icon) throw new Error(`Unknown simple-icons export: ${n}`);
    return `export const ${n} = { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} };`;
  })
  .join('\n');

writeFileSync(
  new URL('../src/lib/brandIcons.ts', import.meta.url),
  `// Generated by scripts/extract-brand-icons.mjs from simple-icons (CC0-1.0). Do not edit.\nexport interface BrandIconData {\n  title: string;\n  path: string;\n}\n\n${body}\n`,
);
console.log(`Wrote ${names.length} icons to src/lib/brandIcons.ts`);
